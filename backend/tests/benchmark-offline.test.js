test('Benchmark Suite: Offline Ollama Pipeline Evaluates 12 Benchmark Questions', async () => {
  let solvedCount = 0;
  let correctOptionCount = 0;
  let uncertainCount = 0;
  const latencies = [];

  for (const item of BENCHMARK_DATASET) {
    const t0 = Date.now();
    const result = await callOllama(
      {
        model: 'gemma3:4b',
        question: item.question,
        options: item.options,
        questionType: item.type,
        image: item.image,
        ollamaUrl: `http://127.0.0.1:${mockPort}`
      },
      { skipModelValidation: true }
    );
    const elapsed = Date.now() - t0;
    latencies.push(elapsed);

    assert.ok(result);
    assert.equal(result.status, 'success');
    assert.ok(result.answer && result.answer.length > 0);

    // Unnecessary uncertainty check
    if (result.option === 'UNCERTAIN' || result.answer.includes('UNCERTAIN')) {
      uncertainCount++;
    }

    if (item.expectedOption) {
      if (result.option === item.expectedOption) {
        correctOptionCount++;
      }
    } else if (item.expectedAnswer) {
      if (result.answer.includes(item.expectedAnswer)) {
        correctOptionCount++;
      }
    }
    solvedCount++;
  }

  const avgLatency = latencies.reduce((a, b) => a + b, 0) / latencies.length;
  const accuracyPct = Math.round((correctOptionCount / solvedCount) * 100);
  const uncertaintyPct = Math.round((uncertainCount / solvedCount) * 100);

  // Assertions
  assert.equal(solvedCount, 12, 'All 12 benchmark questions must be solved');
  assert.equal(uncertaintyPct, 0, 'Unnecessary uncertainty rate must be 0% for solvable questions');
  assert.equal(accuracyPct, 100, 'Mock benchmark accuracy must be 100% against benchmark definitions');
  assert.ok(avgLatency < 500, 'Average mock pipeline latency must be under 500ms');
});

