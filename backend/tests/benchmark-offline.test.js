// Mock server for automated regression and benchmark testing
let mockServer;
let mockPort;
const mockAnswers = new Map();

// Populate standard mock answers
BENCHMARK_DATASET.forEach(bm => {
  mockAnswers.set(bm.id, {
    option: bm.expectedOption || '',
    answer: bm.expectedAnswer || (bm.options.find(o => o.id === bm.expectedOption)?.text || 'Correct'),
    reason: bm.reason,
    confidence: 0.95,
    status: 'success'
  });
});

test.before(async () => {
  mockServer = http.createServer((req, res) => {
    if (req.method === 'GET' && req.url === '/api/tags') {
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({
        models: [
          {
            name: 'gemma3:4b',
            model: 'gemma3:4b',
            size: 3350272403,
            details: { family: 'gemma3', families: ['gemma3', 'clip'], parameter_size: '3.9B' },
            capabilities: ['completion', 'vision']
          }
        ]
      }));
      return;
    }

    if (req.method === 'POST' && req.url === '/api/generate') {
      let body = '';
      req.on('data', chunk => { body += chunk; });
      req.on('end', () => {
        const parsed = JSON.parse(body);
        // Find matching benchmark question
        const matchedBm = BENCHMARK_DATASET.find(b =>
          parsed.prompt.includes(b.question.slice(0, 30))
        );

        const ansObj = matchedBm && mockAnswers.get(matchedBm.id)
          ? mockAnswers.get(matchedBm.id)
          : { option: 'A', answer: 'Mocked Answer', reason: 'Verified', confidence: 0.95, status: 'success' };

        res.writeHead(200, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({
          model: parsed.model,
          response: JSON.stringify(ansObj),
          done: true,
          prompt_eval_count: 85,
          eval_count: 42
        }));
      });
      return;
    }

    res.writeHead(404);
    res.end();
  });

  await new Promise(resolve => {
    mockServer.listen(0, '127.0.0.1', () => {
      mockPort = mockServer.address().port;
      resolve();
    });
  });
});

test.after(async () => {
  if (mockServer) {
    await new Promise(r => mockServer.close(r));
  }
});

